// Build a self-contained Tampermonkey script from the extension's shared helpers.
const fs = require('node:fs');
const path = require('node:path');
const ROOT = __dirname;
const SCRIPT_PATH = path.join(ROOT, 'tampermonkey', 'unlock-flow.user.js');
const DOWNLOAD_URL = 'https://raw.githubusercontent.com/Kam300/Unlock-Flow/main/tampermonkey/unlock-flow.user.js';

function buildUserscript() {
  const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.json'), 'utf8'));
  const sources = ['hook.js', 'playground.js'].map(file =>
    `// Shared source: ${file}\n${fs.readFileSync(path.join(ROOT, file), 'utf8').replace(/\r\n/g, '\n').trim()}\n`
  );
  const header = [
    '// ==UserScript==',
    '// @name         Unlock Flow — Flow & Playground',
    '// @namespace    https://github.com/Kam300/Unlock-Flow',
    `// @version      ${version}`,
    '// @description  Help with regional access to Google Flow and the Playground game catalog.',
    '// @description:ru Помощь со входом в Google Flow и каталог Playground при региональных ограничениях.',
    '// @author       TotalCodeAdmin',
    '// @homepageURL  https://github.com/Kam300/Unlock-Flow',
    '// @supportURL   https://t.me/TotalC0de',
    `// @updateURL    ${DOWNLOAD_URL}`,
    `// @downloadURL  ${DOWNLOAD_URL}`,
    '// @match        https://flow.google.com/*',
    '// @match        https://playground.google/*',
    '// @run-at       document-start',
    '// @sandbox      raw',
    '// @grant        none',
    '// @noframes',
    '// ==/UserScript=='
  ].join('\n');
  // Shadow page CommonJS shims so hook.js cannot mistake a page for Node tests.
  const body = `(function () {\n'use strict';\nconst module = undefined;\nif (window.top !== window.self) return;\n\n${sources.join('\n')}\n})();\n`;
  return { version, text: `${header}\n\n// Generated by pack-userscript.js; edit the shared helpers instead.\n${body}` };
}

function writeUserscript() {
  const { version, text } = buildUserscript();
  const asset = path.join(ROOT, 'dist', `Unlock-Flow-Tampermonkey-v${version}.user.js`);
  for (const target of [SCRIPT_PATH, asset]) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text, 'utf8');
  }
  console.log(`Created Tampermonkey script v${version}`);
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const { text } = buildUserscript();
    if (!fs.existsSync(SCRIPT_PATH) || fs.readFileSync(SCRIPT_PATH, 'utf8').replace(/\r\n/g, '\n') !== text) {
      console.error('Tampermonkey script is stale. Run node pack-userscript.js.');
      process.exitCode = 1;
    }
  } else writeUserscript();
}

module.exports = { buildUserscript, writeUserscript };
